import { CATALOG, catalogEntry, withNames } from "./catalog.js";
import { toMermaid } from "./export.js";
import { describeIntegrations, generateWorkflows, type Workflow } from "./flows.js";
import { ancestorsOf, type DiagramModel, nodeById } from "./model.js";
import { compileTerraform } from "./terraform.js";
import { validateModel } from "./validate.js";

/**
 * A complete architecture document in Markdown: overview, diagram (Mermaid), workflows,
 * how each integration works, review findings and what Terraform would deploy.
 * Renders in GitHub, GitLab, Notion, Confluence and most wikis.
 */
export function toArchitectureDoc(model: DiagramModel, title: string, workflows: Workflow[] = generateWorkflows(model)): string {
  const m = withNames(model);
  const L: string[] = [];
  const name = (id: string) => nodeById(m, id)?.label ?? id;
  const resources = m.nodes.filter((n) => !catalogEntry(n.kind)?.container);
  const integrations = new Map(describeIntegrations(m).map((i) => [i.edgeId, i]));
  const tf = compileTerraform(m);
  const issues = validateModel(m);

  L.push(`# ${title}`, "");
  L.push(
    `${resources.length} resources, ${m.edges.length} connections and ${workflows.length} workflow${workflows.length === 1 ? "" : "s"} on Google Cloud. Generated by ArchCanvas from the architecture diagram.`,
    "",
  );

  L.push("## Diagram", "", "```mermaid", toMermaid(m).trimEnd(), "```", "");

  L.push("## Components", "", "| Component | Type | Where |", "|---|---|---|");
  const order = new Map(CATALOG.map((c, i) => [c.kind, i]));
  for (const n of [...resources].sort((a, b) => (order.get(a.kind) ?? 99) - (order.get(b.kind) ?? 99)))
    L.push(`| ${esc(n.label)} | ${catalogEntry(n.kind)?.label ?? n.kind} | ${esc(ancestorsOf(m, n.id).reverse().map((a) => a.label).join(" › ") || "—")} |`);
  L.push("");

  L.push("## Workflows", "");
  if (!workflows.length) L.push("_No connections yet._", "");
  for (const w of workflows) {
    L.push(`### ${w.title}`, "", `**Trigger:** ${w.trigger}. **Mode:** ${w.mode === "async" ? "asynchronous" : "synchronous"}.`, "", w.summary, "");
    w.steps.forEach((s, i) => L.push(`${i + 1}. **${esc(name(s.from))} → ${esc(name(s.to))}**${s.mode === "async" ? " _(async)_" : ""}: ${s.text}`));
    L.push("");
  }

  L.push("## How each integration works", "");
  for (const e of m.edges) {
    const i = integrations.get(e.id);
    if (!i) continue;
    L.push(`### ${esc(name(e.from))} → ${esc(name(e.to))}`, "", `_${i.pattern}${i.mode === "async" ? ", asynchronous" : ""}._ ${i.summary}`, "");
    section(L, "How it works", i.howItWorks);
    section(L, "Security", i.security);
    section(L, "Configuration", i.config.map((c) => `\`${c.split(" = ")[0]}\`${c.includes(" = ") ? ` = ${c.split(" = ").slice(1).join(" = ")}` : ""}`));
    section(L, "Watch out for", i.considerations);
    if (i.terraform.length) section(L, "Terraform", i.terraform.map((r) => `\`${r}\``));
    if (!i.mapped) L.push("> Documentation only: this connection is not deployed by the generated Terraform.", "");
  }

  L.push("## Review", "");
  if (!issues.length) L.push("No issues found.", "");
  for (const sev of ["error", "warning", "suggestion"] as const) {
    const list = issues.filter((x) => x.severity === sev);
    if (list.length) section(L, sev === "error" ? "Errors" : sev === "warning" ? "Warnings" : "Suggestions", list.map((x) => x.message));
  }

  L.push("## Deployment", "", `The generated Terraform (google provider) creates **${tf.resources.length} resources** in ${tf.files.map((f) => `\`${f.path}\``).join(", ")}.`, "");
  L.push("```bash", "terraform init", "terraform plan -var project_id=YOUR_PROJECT", "```", "");
  return L.join("\n");
}

function section(L: string[], heading: string, items: string[]) {
  if (!items.length) return;
  L.push(`**${heading}**`, "", ...items.map((x) => `- ${x}`), "");
}

const esc = (s: string) => s.replace(/\|/g, "\\|");
